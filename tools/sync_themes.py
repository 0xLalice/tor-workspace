#!/usr/bin/env python3
"""Generate QML bootstrap data from the validated JSON theme sources."""
import argparse
import json
import re
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))
from preset_schema import validate

def outputs(root=ROOT):
    names=json.loads((root/'assets/theme-catalog.json').read_text())
    if not names or any(not isinstance(name,str) or not re.fullmatch(r'[a-zA-Z0-9_-]+',name) for name in names): raise ValueError('Invalid theme catalog')
    paths=[root/'assets/themes'/(name+'.json') for name in names]
    entries=[validate(json.loads(path.read_text())) for path in paths]
    if not entries or entries[0]['id']!='original': raise ValueError('Missing default theme')
    if len({entry['id'] for entry in entries})!=len(entries): raise ValueError('Duplicate bundled theme ids')
    contract=json.loads((root/'assets/theme-style.json').read_text())
    return {
      'ui/theme/BuiltinThemes.js':'.pragma library\n// Generated by tools/sync_themes.py; edit assets/themes/*.json.\nvar entries = '+json.dumps(entries,indent=2)+'\n',
      'ui/theme/DesignDefinitions.js':'.pragma library\n// Generated from assets/theme-style.json by tools/sync_themes.py.\nvar contract = '+json.dumps(contract,indent=2)+'\n'+(root/'tools/theme_style_runtime.js').read_text(),
    }

def sync(root=ROOT,check=False):
    for name,content in outputs(root).items():
        path=root/name
        if check:
            if not path.exists() or path.read_text()!=content: raise ValueError('Stale generated theme data: '+name)
        else: path.write_text(content)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    sync(check=parser.parse_args().check)
